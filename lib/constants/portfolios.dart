/// The portfolios the EB can pick when building a speakers' list in EB Tools.
///
/// Every UN member state, the observers and a few common MUN entities, each with its
/// flag code (ISO 3166-1 alpha-2, lower case; the server and the smartboard use the same
/// codes) and the other names delegates use for it. Anything not here can still be added
/// as a person (shown with a person icon).
class Portfolio {
  const Portfolio(this.name, this.code,
      [this.aliases = const [], this.tag, this.detail]);

  final String name;

  /// The flag (ISO alpha-2, lower case); null for a person.
  final String? code;
  final List<String> aliases;

  /// A person's party abbreviation (PSC), shown as a badge instead of a flag.
  final String? tag;

  /// A person's party, in full.
  final String? detail;
}

/// A committee's matrix (GET /public/committees/{id}/portfolios) as portfolios to search.
/// A country also answers to the names in [kPortfolios] for its flag ("usa" finds "United
/// States of America", "ivory" finds "Côte d'Ivoire"); a PSC member to their party.
List<Portfolio> matrixPortfolios(List<dynamic> json) {
  final byCode = {for (final p in kPortfolios) p.code: p};
  return [
    for (final raw in json)
      () {
        final j = raw as Map<String, dynamic>;
        final name = j['name'] as String;
        final code = j['code'] as String?;
        final tag = j['tag'] as String?;
        final detail = j['detail'] as String?;
        final known = code == null ? null : byCode[code];
        final aliases = <String>{
          if (known != null) ...[known.name, ...known.aliases],
          if (tag != null) tag,
          if (detail != null) detail,
        }..remove(name);
        return Portfolio(name, code, aliases.toList(), tag, detail);
      }(),
  ];
}

